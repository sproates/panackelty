function encodeBody(type) {
  if (type === 'SignatureType') return 'encode_u32(pool.type_indices.get(value))';
  if (type.startsWith('[')) return 'mut chunks: [Bytes] = [encode_u32(value.len())]\n' +
    '  for item in value { chunks = chunks.append(encode_' + identifiers(type.slice(1, -1)) + '(pool, item)) }\n' +
    '  source_map_join(chunks, 0, chunks.len())';
  if (type.startsWith('?')) return 'match value {\n    None() => encode_u32(0),\n' +
    '    Some(item) => encode_u32(1).join(encode_' + identifiers(type.slice(1)) + '(pool, item))\n  }';
  if (records[type]) return 'byte_buffer.empty()' + records[type]
    .filter(([, item]) => item).map(([field, item]) => '.join(encode_' + identifiers(item) + '(pool, value.' + field + '))').join('');
  const arms = enums[type].map(([variant, ...payload], tag) => {
    const names = payload.map((_, index) => 'v' + index).join(', ');
    return '    ' + variant + '(' + names + ') => encode_u32(' + tag + ')' +
      payload.map((item, index) => item ? '.join(encode_' + identifiers(item) + '(pool, v' + index + '))' : '').join('');
  });
  if (type === 'Expr') for (const [variant, count] of unsupportedExpressions) {
    arms.push('    ' + variant + '(' + Array.from({ length: count }, (_, i) => 'unused' + i).join(', ') + ') => encode_u32(999)');
  }
  return 'match value {\n' + arms.join(',\n') + '\n  }';
}
